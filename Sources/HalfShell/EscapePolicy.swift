import Foundation

/// 탈출구가 준비되지 않았으면 유일한 화면을 끄지 않는다.
///
/// 화면 복구 단축키(Command 연타)는 자동 복구가 어떤 이유로든 실패해 화면이 검게 남았을 때
/// 손만으로 빠져나오는 유일한 수단이다. 그런데 손쉬운 사용 권한이 없으면 조용히 죽어 있다.
///
/// 10/24 에 실제로 그렇게 됐다. 서명 인증서를 Developer ID 로 바꾸자 macOS 가 다른 앱으로
/// 보고 권한을 풀었고, 개발자는 다시 켜라는 안내를 받고도 놓쳤다. 이튿날 확인하기까지
/// **내장이 꺼진 채로, 탈출구 없이** 반나절을 썼다. 메뉴 구석의 "작동 안 함" 표시로는
/// 부족했다(POSTMORTEM 규칙 9 — 로그나 구석에 남긴 경고는 없는 것과 같다).
///
/// 앱 실행 자체를 막지는 않는다. 앱이 떠 있어야 왜 안 되는지 알려 줄 수 있고, 외장을
/// 빼면 켜 주는 복구도 계속 돌아야 한다. 막는 것은 **위험한 동작 하나 — 내장 끄기**뿐이다.
/// 권한이 풀리면 꺼 둔 내장도 되살린다. 탈출구 없는 상태를 남기지 않고, 사용자가
/// "왜 안 꺼지지?" 하고 곧바로 알아채게 하려는 것이다.
enum EscapePolicy {
    /// 내장을 끌 수 있는가.
    static func mayTurnOff(escapeReady: Bool) -> Bool { escapeReady }

    /// 탈출구 없이 꺼져 있는 내장을 되살려야 하는가.
    /// 뚜껑이 닫혀 있으면 꺼진 것이 정상(클램쉘)이라 손대지 않는다(사건 5).
    static func mustRestore(escapeReady: Bool, builtinOff: Bool, lidClosed: Bool) -> Bool {
        !escapeReady && builtinOff && !lidClosed
    }
}
